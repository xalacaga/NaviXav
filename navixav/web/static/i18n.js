  function normalise(value) {
    return Object.prototype.hasOwnProperty.call(TRANSLATIONS, value) ? value : "fr";
  }

  function getLanguage() {
    return normalise(localStorage.getItem(STORAGE_KEY) || "fr");
  }

  /** Vrai dès que l'utilisateur a explicitement choisi une langue. */
  function hasLanguage() {
    return Boolean(localStorage.getItem(STORAGE_KEY));
  }

  /** Langue proposée au premier lancement, déduite du système. */
  function suggestedLanguage() {
    for (const tag of navigator.languages || [navigator.language || ""]) {
      const candidate = String(tag).slice(0, 2).toLowerCase();
      if (Object.prototype.hasOwnProperty.call(TRANSLATIONS, candidate)) {
        return candidate;
      }
    }
    return "fr";
  }

  function t(key) {
    const language = getLanguage();
    return TRANSLATIONS[language][key] || TRANSLATIONS.en[key] || TRANSLATIONS.fr[key] || key;
  }

  function setNodeText(node, value) {
    if (!node.children.length) {
      node.textContent = value;
      return;
    }
    const textNode = Array.from(node.childNodes).find(
      (child) => child.nodeType === Node.TEXT_NODE && child.nodeValue.trim()
    );
    if (textNode) textNode.nodeValue = value;
    else node.append(document.createTextNode(value));
  }

  function apply() {
    const language = getLanguage();
    document.documentElement.lang = language;
    for (const [selector, key] of Object.entries(ELEMENTS)) {
      const node = document.querySelector(selector);
      if (node) setNodeText(node, t(key));
    }
    for (const [selector, key] of Object.entries(TITLES)) {
      const node = document.querySelector(selector);
      if (node) node.title = t(key);
    }
    const close = document.querySelector("#settings-close");
    if (close) close.setAttribute("aria-label", t("close"));
    const basemapStyle = document.querySelector("#map-basemap-style");
    if (basemapStyle) basemapStyle.setAttribute("aria-label", t("basemap_style"));
    for (const id of ["#settings-username", "#welcome-username"]) {
      const node = document.querySelector(id);
      if (node) node.placeholder = t("pilot_username_placeholder");
    }
    for (const id of ["#settings-pilot-id", "#welcome-pilot-id"]) {
      const node = document.querySelector(id);
      if (node) node.placeholder = t("pilot_id_placeholder");
    }
    for (const id of ["#settings-language", "#welcome-language"]) {
      const select = document.querySelector(id);
      if (select) select.value = language;
    }
  }

  function setLanguage(language) {
    localStorage.setItem(STORAGE_KEY, normalise(language));
    apply();
    window.dispatchEvent(new CustomEvent("navixav:languagechange"));
  }

  window.I18N = { apply, getLanguage, hasLanguage, setLanguage, suggestedLanguage, t };
